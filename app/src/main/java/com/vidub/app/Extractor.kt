package com.vidub.app

import okhttp3.OkHttpClient
import okhttp3.RequestBody.Companion.toRequestBody
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.downloader.Downloader
import org.schabi.newpipe.extractor.downloader.Request
import org.schabi.newpipe.extractor.downloader.Response
import org.schabi.newpipe.extractor.exceptions.ReCaptchaException
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.StreamInfo
import java.util.concurrent.TimeUnit

const val USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; rv:153.0) Gecko/20100101 Firefox/153.0"

/** Cầu nối giữa NewPipeExtractor và OkHttp. */
class AppDownloader : Downloader() {
    private val client = OkHttpClient.Builder()
        .readTimeout(30, TimeUnit.SECONDS)
        .build()

    override fun execute(request: Request): Response {
        val body = request.dataToSend()?.toRequestBody(null)
        val builder = okhttp3.Request.Builder()
            .method(request.httpMethod(), body)
            .url(request.url())
            .addHeader("User-Agent", USER_AGENT)

        for ((name, values) in request.headers()) {
            builder.removeHeader(name)
            values.forEach { builder.addHeader(name, it) }
        }

        client.newCall(builder.build()).execute().use { resp ->
            if (resp.code == 429) {
                throw ReCaptchaException("reCaptcha Challenge requested", request.url())
            }
            return Response(
                resp.code,
                resp.message,
                resp.headers.toMultimap(),
                resp.body?.string() ?: "",
                resp.request.url.toString()
            )
        }
    }
}

data class SubTrack(val lang: String, val auto: Boolean, val url: String)

data class VideoData(
    val title: String,
    val videoUrl: String?,   // luồng có cả hình + tiếng (progressive)
    val audioUrl: String?,   // chỉ dùng khi phải ghép hình và tiếng riêng
    val hlsUrl: String?,     // dự phòng (livestream)
    val subs: List<SubTrack>
)

object YtFetcher {
    private var inited = false

    @Synchronized
    private fun init() {
        if (!inited) {
            NewPipe.init(AppDownloader())
            inited = true
        }
    }

    /** Chạy trên luồng nền (IO). */
    fun fetch(url: String): VideoData {
        init()
        val info = StreamInfo.getInfo(ServiceList.YouTube, url)

        val muxed = info.videoStreams
            .filter { it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && it.isUrl }
        // Ưu tiên 720p trở xuống cho nhẹ; nếu không có thì lấy bản thấp nhất
        val bestMuxed = muxed.filter { it.height in 1..720 }.maxByOrNull { it.height }
            ?: muxed.minByOrNull { it.height }

        var video: String? = bestMuxed?.content
        var audio: String? = null

        if (video == null) {
            val vo = info.videoOnlyStreams
                .filter { it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && it.isUrl && it.height in 1..720 }
                .maxByOrNull { it.height }
            val au = info.audioStreams
                .filter { it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && it.isUrl }
                .maxByOrNull { it.averageBitrate }
            if (vo != null && au != null) {
                video = vo.content
                audio = au.content
            }
        }

        val subs = info.subtitles
            .map { SubTrack(it.languageTag ?: "", it.isAutoGenerated, it.content ?: "") }
            .filter { it.lang.isNotEmpty() && it.url.isNotEmpty() }

        return VideoData(
            title = info.name ?: "",
            videoUrl = video,
            audioUrl = audio,
            hlsUrl = info.hlsUrl?.takeIf { it.isNotEmpty() },
            subs = subs
        )
    }
}
